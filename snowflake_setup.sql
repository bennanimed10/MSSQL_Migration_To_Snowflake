-- Create stored procedure to load data from S3 to Snowflake
CREATE OR REPLACE PROCEDURE CAS_DATA.RAW.LOAD_S3_DATA(
    TABLE_NAME STRING,
    FILE_PATTERN STRING,
    SNAPSHOT_DATE STRING
)
RETURNS STRING
LANGUAGE JAVASCRIPT
AS
$$
    // Construct the COPY command
    var copy_command = `
        COPY INTO CAS_DATA.RAW.${TABLE_NAME}
        FROM @CAS_DATA.RAW.S3_STAGE/${SNAPSHOT_DATE}/
        FILES = ('${FILE_PATTERN}')
        FILE_FORMAT = (FORMAT_NAME = CAS_DATA.RAW.CSV_FORMAT)
        PATTERN = '.*${FILE_PATTERN}'
        ON_ERROR = 'CONTINUE'
    `;
    
    // Execute the COPY command
    try {
        var stmt = snowflake.createStatement({sqlText: copy_command});
        var result = stmt.execute();
        return "Successfully loaded data into " + TABLE_NAME;
    } catch (err) {
        return "Error loading data: " + err;
    }
$$;

-- Create a task to load data daily
CREATE OR REPLACE TASK CAS_DATA.RAW.LOAD_DAILY_DATA
    WAREHOUSE = COMPUTE_WH
    SCHEDULE = 'USING CRON 0 2 * * * America/New_York'
AS
BEGIN
    -- Get yesterday's date in YYYY/MM/DD format for the S3 path
    SET snapshot_date = (SELECT TO_CHAR(DATEADD(DAY, -1, CURRENT_DATE()), 'YYYY/MM/DD'));
    
    -- Load each table
    CALL CAS_DATA.RAW.LOAD_S3_DATA('TBL_CONTRACT', 'tbl_contract.csv.gz', $snapshot_date);
    CALL CAS_DATA.RAW.LOAD_S3_DATA('TBL_CUSTOMER', 'tbl_customer.csv.gz', $snapshot_date);
    CALL CAS_DATA.RAW.LOAD_S3_DATA('TBL_VEHICLE', 'tbl_vehicle.csv.gz', $snapshot_date);
END;

