USE SCHEMA AUDIT;

-- Data quality summary view
CREATE OR REPLACE VIEW V_DATA_QUALITY_SUMMARY AS
SELECT 
    'CUSTOMERS' AS TABLE_NAME,
    COUNT(*) AS TOTAL_RECORDS,
    COUNT(CASE WHEN EMAIL IS NULL OR EMAIL = '' THEN 1 END) AS MISSING_EMAIL,
    COUNT(CASE WHEN PHONE IS NULL OR PHONE = '' THEN 1 END) AS MISSING_PHONE,
    COUNT(CASE WHEN ADDRESS IS NULL OR ADDRESS = '' THEN 1 END) AS MISSING_ADDRESS,
    COUNT(CASE WHEN DMS_TIMESTAMP IS NULL THEN 1 END) AS MISSING_DMS_TIMESTAMP
FROM MIGRATION_DB.PUBLIC.CUSTOMERS

UNION ALL

SELECT 
    'ORDERS' AS TABLE_NAME,
    COUNT(*) AS TOTAL_RECORDS,
    COUNT(CASE WHEN CUSTOMER_ID IS NULL THEN 1 END) AS MISSING_CUSTOMER_ID,
    COUNT(CASE WHEN TOTAL_AMOUNT IS NULL OR TOTAL_AMOUNT <= 0 THEN 1 END) AS INVALID_AMOUNT,
    COUNT(CASE WHEN ORDER_STATUS IS NULL OR ORDER_STATUS = '' THEN 1 END) AS MISSING_STATUS,
    COUNT(CASE WHEN DMS_TIMESTAMP IS NULL THEN 1 END) AS MISSING_DMS_TIMESTAMP
FROM MIGRATION_DB.PUBLIC.ORDERS

UNION ALL

SELECT 
    'PRODUCTS' AS TABLE_NAME,
    COUNT(*) AS TOTAL_RECORDS,
    COUNT(CASE WHEN PRODUCT_NAME IS NULL OR PRODUCT_NAME = '' THEN 1 END) AS MISSING_NAME,
    COUNT(CASE WHEN UNIT_PRICE IS NULL OR UNIT_PRICE <= 0 THEN 1 END) AS INVALID_PRICE,
    COUNT(CASE WHEN PRODUCT_CODE IS NULL OR PRODUCT_CODE = '' THEN 1 END) AS MISSING_CODE,
    COUNT(CASE WHEN DMS_TIMESTAMP IS NULL THEN 1 END) AS MISSING_DMS_TIMESTAMP
FROM MIGRATION_DB.PUBLIC.PRODUCTS;

-- Migration progress view
CREATE OR REPLACE VIEW V_MIGRATION_PROGRESS AS
SELECT 
    TABLE_NAME,
    COUNT(*) AS TOTAL_MIGRATIONS,
    SUM(CASE WHEN STATUS = 'SUCCESS' THEN 1 ELSE 0 END) AS SUCCESSFUL_MIGRATIONS,
    SUM(CASE WHEN STATUS = 'FAILED' THEN 1 ELSE 0 END) AS FAILED_MIGRATIONS,
    ROUND(
        (SUM(CASE WHEN STATUS = 'SUCCESS' THEN 1 ELSE 0 END) * 100.0 / COUNT(*)), 
        2
    ) AS SUCCESS_RATE_PERCENT,
    SUM(ROWS_PROCESSED) AS TOTAL_ROWS_PROCESSED,
    AVG(DURATION_SECONDS) AS AVG_DURATION_SECONDS,
    MAX(END_TIME) AS LAST_MIGRATION_TIME
FROM MIGRATION_LOG
GROUP BY TABLE_NAME
ORDER BY LAST_MIGRATION_TIME DESC;

