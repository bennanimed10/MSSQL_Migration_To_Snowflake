-- Views for Analytics
-- =====================================================

-- Customer summary view
CREATE OR REPLACE VIEW V_CUSTOMER_SUMMARY AS
SELECT 
    c.CUSTOMER_ID,
    c.FIRST_NAME,
    c.LAST_NAME,
    c.EMAIL,
    c.CITY,
    c.STATE,
    c.COUNTRY,
    COUNT(o.ORDER_ID) AS TOTAL_ORDERS,
    COALESCE(SUM(o.TOTAL_AMOUNT), 0) AS TOTAL_SPENT,
    COALESCE(AVG(o.TOTAL_AMOUNT), 0) AS AVG_ORDER_VALUE,
    MAX(o.ORDER_DATE) AS LAST_ORDER_DATE,
    MIN(o.ORDER_DATE) AS FIRST_ORDER_DATE,
    DATEDIFF('day', MIN(o.ORDER_DATE), MAX(o.ORDER_DATE)) AS CUSTOMER_LIFETIME_DAYS,
    c.CREATED_DATE AS CUSTOMER_SINCE
FROM CUSTOMERS c
LEFT JOIN ORDERS o ON c.CUSTOMER_ID = o.CUSTOMER_ID
WHERE c.IS_ACTIVE = TRUE
GROUP BY 
    c.CUSTOMER_ID, c.FIRST_NAME, c.LAST_NAME, c.EMAIL,
    c.CITY, c.STATE, c.COUNTRY, c.CREATED_DATE;

-- Order details view
CREATE OR REPLACE VIEW V_ORDER_DETAILS AS
SELECT 
    o.ORDER_ID,
    o.CUSTOMER_ID,
    c.FIRST_NAME || ' ' || c.LAST_NAME AS CUSTOMER_NAME,
    c.EMAIL AS CUSTOMER_EMAIL,
    o.ORDER_DATE,
    o.ORDER_STATUS,
    o.TOTAL_AMOUNT,
    o.CURRENCY,
    o.PAYMENT_METHOD,
    COUNT(oi.ORDER_ITEM_ID) AS TOTAL_ITEMS,
    SUM(oi.QUANTITY) AS TOTAL_QUANTITY,
    o.CREATED_DATE
FROM ORDERS o
JOIN CUSTOMERS c ON o.CUSTOMER_ID = c.CUSTOMER_ID
LEFT JOIN ORDER_ITEMS oi ON o.ORDER_ID = oi.ORDER_ID
GROUP BY 
    o.ORDER_ID, o.CUSTOMER_ID, c.FIRST_NAME, c.LAST_NAME, c.EMAIL,
    o.ORDER_DATE, o.ORDER_STATUS, o.TOTAL_AMOUNT, o.CURRENCY,
    o.PAYMENT_METHOD, o.CREATED_DATE;

-- Product performance view
CREATE OR REPLACE VIEW V_PRODUCT_PERFORMANCE AS
SELECT 
    p.PRODUCT_ID,
    p.PRODUCT_NAME,
    p.PRODUCT_CODE,
    p.CATEGORY,
    p.BRAND,
    p.UNIT_PRICE,
    p.STOCK_QUANTITY,
    COALESCE(SUM(oi.QUANTITY), 0) AS TOTAL_SOLD,
    COALESCE(SUM(oi.LINE_TOTAL), 0) AS TOTAL_REVENUE,
    COALESCE(COUNT(DISTINCT oi.ORDER_ID), 0) AS ORDERS_COUNT,
    COALESCE(AVG(oi.UNIT_PRICE), p.UNIT_PRICE) AS AVG_SELLING_PRICE,
    p.IS_ACTIVE,
    p.CREATED_DATE
FROM PRODUCTS p
LEFT JOIN ORDER_ITEMS oi ON p.PRODUCT_ID = oi.PRODUCT_ID
GROUP BY 
    p.PRODUCT_ID, p.PRODUCT_NAME, p.PRODUCT_CODE, p.CATEGORY,
    p.BRAND, p.UNIT_PRICE, p.STOCK_QUANTITY, p.IS_ACTIVE, p.CREATED_DATE;

