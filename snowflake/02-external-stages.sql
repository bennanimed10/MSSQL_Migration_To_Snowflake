-- Create views to monitor stage and pipe status
USE SCHEMA MIGRATION_DB.AUDIT;

CREATE VIEW IF NOT EXISTS V_STAGE_STATUS AS
SELECT 
    STAGE_NAME,
    STAGE_URL,
    STAGE_TYPE,
    CREATED,
    LAST_ALTERED,
    COMMENT
FROM INFORMATION_SCHEMA.STAGES
WHERE STAGE_SCHEMA = 'PUBLIC'
ORDER BY STAGE_NAME;

CREATE VIEW IF NOT EXISTS V_PIPE_STATUS AS
SELECT 
    PIPE_NAME,
    IS_AUTOINGEST_ENABLED,
    NOTIFICATION_CHANNEL_NAME,
    PIPE_EXECUTION_PAUSED,
    DEFINITION,
    CREATED,
    LAST_ALTERED,
    COMMENT
FROM INFORMATION_SCHEMA.PIPES
WHERE PIPE_SCHEMA = 'PUBLIC'
ORDER BY PIPE_NAME;

-- Create stored procedure to refresh stages
USE SCHEMA MIGRATION_DB.PUBLIC;

CREATE OR REPLACE PROCEDURE SP_REFRESH_STAGES()
RETURNS STRING
LANGUAGE SQL
AS
$$
DECLARE
    result STRING DEFAULT '';
BEGIN
    -- Refresh directory tables for all stages
    ALTER STAGE STG_DMS_FULL_LOAD REFRESH;
    ALTER STAGE STG_DMS_CDC REFRESH;
    ALTER STAGE STG_MANUAL_LOAD REFRESH;
    ALTER STAGE STG_CONFIG REFRESH;
    ALTER STAGE STG_LOGS REFRESH;
    
    result := 'All stages refreshed successfully at ' || CURRENT_TIMESTAMP()::STRING;
    RETURN result;
END;
$$;

-- Create stored procedure to check pipe status
CREATE OR REPLACE PROCEDURE SP_CHECK_PIPE_STATUS()
RETURNS TABLE (PIPE_NAME STRING, STATUS STRING, PENDING_FILES NUMBER, LAST_RECEIVED_TIME TIMESTAMP_NTZ)
LANGUAGE SQL
AS
$$
BEGIN
    RETURN TABLE(
        SELECT 
            PIPE_NAME,
            CASE 
                WHEN PIPE_EXECUTION_PAUSED THEN 'PAUSED'
                WHEN IS_AUTOINGEST_ENABLED THEN 'RUNNING'
                ELSE 'STOPPED'
            END AS STATUS,
            PENDING_FILE_COUNT AS PENDING_FILES,
            LAST_RECEIVED_MESSAGE_TIMESTAMP AS LAST_RECEIVED_TIME
        FROM TABLE(INFORMATION_SCHEMA.PIPE_USAGE_HISTORY(
            DATE_RANGE_START => DATEADD('day', -1, CURRENT_DATE()),
            DATE_RANGE_END => CURRENT_DATE()
        ))
        WHERE PIPE_NAME IN ('PIPE_DMS_FULL_LOAD', 'PIPE_DMS_CDC')
    );
END;
$$;

-- Create stored procedure to list stage files
CREATE OR REPLACE PROCEDURE SP_LIST_STAGE_FILES(STAGE_NAME STRING)
RETURNS TABLE (FILE_NAME STRING, FILE_SIZE NUMBER, LAST_MODIFIED TIMESTAMP_NTZ)
LANGUAGE SQL
AS
$$
DECLARE
    query STRING;
BEGIN
    query := 'LIST @' || STAGE_NAME;
    RETURN TABLE(
        SELECT 
            "name" AS FILE_NAME,
            "size" AS FILE_SIZE,
            "last_modified" AS LAST_MODIFIED
        FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()))
    );
END;
$$;

