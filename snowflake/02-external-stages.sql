-- Create pipes for automatic data ingestion
-- Pipe for full load data
CREATE PIPE IF NOT EXISTS PIPE_DMS_FULL_LOAD
    AUTO_INGEST = TRUE
    AS
    COPY INTO MIGRATION_DB.STAGING.TEMP_FULL_LOAD
    FROM @STG_DMS_FULL_LOAD
    FILE_FORMAT = PARQUET_FORMAT
    MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
    ON_ERROR = 'CONTINUE'
    PURGE = FALSE
    COMMENT = 'Auto-ingest pipe for DMS full load data';

-- Pipe for CDC data
CREATE PIPE IF NOT EXISTS PIPE_DMS_CDC
    AUTO_INGEST = TRUE
    AS
    COPY INTO MIGRATION_DB.STAGING.TEMP_CDC
    FROM @STG_DMS_CDC
    FILE_FORMAT = PARQUET_FORMAT
    MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
    ON_ERROR = 'CONTINUE'
    PURGE = FALSE
    COMMENT = 'Auto-ingest pipe for DMS CDC data';

-- Grant pipe privileges
GRANT OWNERSHIP ON PIPE PIPE_DMS_FULL_LOAD TO ROLE MIGRATION_ADMIN;
GRANT OWNERSHIP ON PIPE PIPE_DMS_CDC TO ROLE MIGRATION_ADMIN;

