-- Create views for monitoring
CREATE VIEW IF NOT EXISTS MIGRATION_DB.AUDIT.V_MIGRATION_SUMMARY AS
SELECT 
    TABLE_NAME,
    COUNT(*) AS TOTAL_RUNS,
    SUM(CASE WHEN STATUS = 'SUCCESS' THEN 1 ELSE 0 END) AS SUCCESSFUL_RUNS,
    SUM(CASE WHEN STATUS = 'FAILED' THEN 1 ELSE 0 END) AS FAILED_RUNS,
    AVG(DURATION_SECONDS) AS AVG_DURATION_SECONDS,
    SUM(ROWS_PROCESSED) AS TOTAL_ROWS_PROCESSED,
    MAX(END_TIME) AS LAST_RUN_TIME,
    MAX(CASE WHEN STATUS = 'SUCCESS' THEN END_TIME END) AS LAST_SUCCESSFUL_RUN
FROM MIGRATION_DB.AUDIT.MIGRATION_LOG
GROUP BY TABLE_NAME;

CREATE VIEW IF NOT EXISTS MIGRATION_DB.AUDIT.V_DATA_QUALITY_SUMMARY AS
SELECT 
    TABLE_NAME,
    CHECK_TYPE,
    COUNT(*) AS TOTAL_CHECKS,
    SUM(CASE WHEN CHECK_RESULT = 'PASS' THEN 1 ELSE 0 END) AS PASSED_CHECKS,
    SUM(CASE WHEN CHECK_RESULT = 'FAIL' THEN 1 ELSE 0 END) AS FAILED_CHECKS,
    ROUND((SUM(CASE WHEN CHECK_RESULT = 'PASS' THEN 1 ELSE 0 END) * 100.0 / COUNT(*)), 2) AS PASS_RATE_PERCENT,
    MAX(CHECK_TIMESTAMP) AS LAST_CHECK_TIME
FROM MIGRATION_DB.AUDIT.DATA_QUALITY_LOG
GROUP BY TABLE_NAME, CHECK_TYPE;

