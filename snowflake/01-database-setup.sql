-- Create file formats for different data types
USE SCHEMA MIGRATION_DB.PUBLIC;

CREATE FILE FORMAT IF NOT EXISTS PARQUET_FORMAT
    TYPE = 'PARQUET'
    COMPRESSION = 'SNAPPY'
    BINARY_AS_TEXT = FALSE
    COMMENT = 'Parquet file format for DMS output';

CREATE FILE FORMAT IF NOT EXISTS CSV_FORMAT
    TYPE = 'CSV'
    FIELD_DELIMITER = ','
    RECORD_DELIMITER = '\n'
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    TRIM_SPACE = TRUE
    ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE
    REPLACE_INVALID_CHARACTERS = TRUE
    DATE_FORMAT = 'YYYY-MM-DD'
    TIME_FORMAT = 'HH24:MI:SS'
    TIMESTAMP_FORMAT = 'YYYY-MM-DD HH24:MI:SS.FF3'
    COMMENT = 'CSV file format for manual data loads';

CREATE FILE FORMAT IF NOT EXISTS JSON_FORMAT
    TYPE = 'JSON'
    COMPRESSION = 'AUTO'
    ENABLE_OCTAL = FALSE
    ALLOW_DUPLICATE = FALSE
    STRIP_OUTER_ARRAY = TRUE
    STRIP_NULL_VALUES = FALSE
    IGNORE_UTF8_ERRORS = FALSE
    COMMENT = 'JSON file format for configuration and metadata';

-- Create sequences for surrogate keys
CREATE SEQUENCE IF NOT EXISTS MIGRATION_DB.METADATA.MIGRATION_LOG_SEQ
    START = 1
    INCREMENT = 1
    COMMENT = 'Sequence for migration log entries';

-- Create metadata tables
USE SCHEMA MIGRATION_DB.METADATA;

CREATE TABLE IF NOT EXISTS MIGRATION_CONFIG (
    CONFIG_ID NUMBER AUTOINCREMENT PRIMARY KEY,
    CONFIG_NAME VARCHAR(100) NOT NULL UNIQUE,
    CONFIG_VALUE VARCHAR(1000),
    CONFIG_TYPE VARCHAR(50) DEFAULT 'STRING',
    DESCRIPTION VARCHAR(500),
    IS_ACTIVE BOOLEAN DEFAULT TRUE,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CREATED_BY VARCHAR(100) DEFAULT CURRENT_USER(),
    UPDATED_BY VARCHAR(100) DEFAULT CURRENT_USER()
);

CREATE TABLE IF NOT EXISTS TABLE_MAPPING (
    MAPPING_ID NUMBER AUTOINCREMENT PRIMARY KEY,
    SOURCE_SCHEMA VARCHAR(100) NOT NULL,
    SOURCE_TABLE VARCHAR(100) NOT NULL,
    TARGET_SCHEMA VARCHAR(100) NOT NULL,
    TARGET_TABLE VARCHAR(100) NOT NULL,
    MIGRATION_TYPE VARCHAR(50) DEFAULT 'FULL_LOAD_AND_CDC',
    IS_ACTIVE BOOLEAN DEFAULT TRUE,
    PRIORITY NUMBER DEFAULT 100,
    BATCH_SIZE NUMBER DEFAULT 10000,
    PARALLEL_LOAD BOOLEAN DEFAULT FALSE,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UNIQUE (SOURCE_SCHEMA, SOURCE_TABLE)
);

-- Create audit tables
USE SCHEMA MIGRATION_DB.AUDIT;

CREATE TABLE IF NOT EXISTS MIGRATION_LOG (
    LOG_ID NUMBER DEFAULT MIGRATION_DB.METADATA.MIGRATION_LOG_SEQ.NEXTVAL PRIMARY KEY,
    MIGRATION_ID VARCHAR(100),
    TABLE_NAME VARCHAR(200),
    OPERATION VARCHAR(50),
    STATUS VARCHAR(50),
    START_TIME TIMESTAMP_NTZ,
    END_TIME TIMESTAMP_NTZ,
    DURATION_SECONDS NUMBER,
    ROWS_PROCESSED NUMBER,
    ROWS_INSERTED NUMBER,
    ROWS_UPDATED NUMBER,
    ROWS_DELETED NUMBER,
    ROWS_FAILED NUMBER,
    ERROR_MESSAGE VARCHAR(4000),
    S3_PATH VARCHAR(1000),
    DMS_TASK_ARN VARCHAR(500),
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CREATED_BY VARCHAR(100) DEFAULT CURRENT_USER()
);

CREATE TABLE IF NOT EXISTS DATA_QUALITY_LOG (
    QUALITY_ID NUMBER AUTOINCREMENT PRIMARY KEY,
    TABLE_NAME VARCHAR(200) NOT NULL,
    CHECK_TYPE VARCHAR(100) NOT NULL,
    CHECK_NAME VARCHAR(200) NOT NULL,
    CHECK_RESULT VARCHAR(50) NOT NULL,
    EXPECTED_VALUE VARIANT,
    ACTUAL_VALUE VARIANT,
    VARIANCE_THRESHOLD NUMBER,
    VARIANCE_ACTUAL NUMBER,
    ERROR_MESSAGE VARCHAR(4000),
    CHECK_TIMESTAMP TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CREATED_BY VARCHAR(100) DEFAULT CURRENT_USER()
);

