-- Use ACCOUNTADMIN role for initial setup
USE ROLE ACCOUNTADMIN;

-- Create database for migration
CREATE DATABASE IF NOT EXISTS MIGRATION_DB
    COMMENT = 'Database for SQL Server to Snowflake migration';

-- Create schemas for different data domains
USE DATABASE MIGRATION_DB;

CREATE SCHEMA IF NOT EXISTS PUBLIC
    COMMENT = 'Main schema for migrated tables';

CREATE SCHEMA IF NOT EXISTS STAGING
    COMMENT = 'Staging area for data processing';

CREATE SCHEMA IF NOT EXISTS AUDIT
    COMMENT = 'Audit and logging tables';

CREATE SCHEMA IF NOT EXISTS METADATA
    COMMENT = 'Migration metadata and configuration';

-- Create warehouse for migration workloads
CREATE WAREHOUSE IF NOT EXISTS MIGRATION_WH
    WITH WAREHOUSE_SIZE = 'MEDIUM'
    AUTO_SUSPEND = 300
    AUTO_RESUME = TRUE
    MIN_CLUSTER_COUNT = 1
    MAX_CLUSTER_COUNT = 3
    SCALING_POLICY = 'STANDARD'
    COMMENT = 'Warehouse for migration operations';

-- Create warehouse for analytics workloads
CREATE WAREHOUSE IF NOT EXISTS ANALYTICS_WH
    WITH WAREHOUSE_SIZE = 'LARGE'
    AUTO_SUSPEND = 600
    AUTO_RESUME = TRUE
    MIN_CLUSTER_COUNT = 1
    MAX_CLUSTER_COUNT = 5
    SCALING_POLICY = 'STANDARD'
    COMMENT = 'Warehouse for analytics and reporting';

-- Create roles for migration
CREATE ROLE IF NOT EXISTS MIGRATION_ADMIN
    COMMENT = 'Admin role for migration operations';

CREATE ROLE IF NOT EXISTS MIGRATION_USER
    COMMENT = 'User role for migration operations';

CREATE ROLE IF NOT EXISTS ANALYTICS_USER
    COMMENT = 'User role for analytics and reporting';

-- Grant privileges to roles
GRANT USAGE ON DATABASE MIGRATION_DB TO ROLE MIGRATION_ADMIN;
GRANT USAGE ON DATABASE MIGRATION_DB TO ROLE MIGRATION_USER;
GRANT USAGE ON DATABASE MIGRATION_DB TO ROLE ANALYTICS_USER;

GRANT ALL PRIVILEGES ON SCHEMA MIGRATION_DB.PUBLIC TO ROLE MIGRATION_ADMIN;
GRANT ALL PRIVILEGES ON SCHEMA MIGRATION_DB.STAGING TO ROLE MIGRATION_ADMIN;
GRANT ALL PRIVILEGES ON SCHEMA MIGRATION_DB.AUDIT TO ROLE MIGRATION_ADMIN;
GRANT ALL PRIVILEGES ON SCHEMA MIGRATION_DB.METADATA TO ROLE MIGRATION_ADMIN;

GRANT USAGE ON SCHEMA MIGRATION_DB.PUBLIC TO ROLE MIGRATION_USER;
GRANT USAGE ON SCHEMA MIGRATION_DB.STAGING TO ROLE MIGRATION_USER;
GRANT SELECT ON ALL TABLES IN SCHEMA MIGRATION_DB.PUBLIC TO ROLE MIGRATION_USER;
GRANT SELECT ON ALL TABLES IN SCHEMA MIGRATION_DB.STAGING TO ROLE MIGRATION_USER;

GRANT USAGE ON SCHEMA MIGRATION_DB.PUBLIC TO ROLE ANALYTICS_USER;
GRANT SELECT ON ALL TABLES IN SCHEMA MIGRATION_DB.PUBLIC TO ROLE ANALYTICS_USER;

-- Grant warehouse usage
GRANT USAGE ON WAREHOUSE MIGRATION_WH TO ROLE MIGRATION_ADMIN;
GRANT USAGE ON WAREHOUSE MIGRATION_WH TO ROLE MIGRATION_USER;
GRANT USAGE ON WAREHOUSE ANALYTICS_WH TO ROLE ANALYTICS_USER;

